#!/usr/bin/env node
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { extractGeometryRuntime } from "./geometry_runtime.mjs";
const source = extractGeometryRuntime(readFileSync("app.html", "utf8"), [
  "planInteriorFloor",
]);
const hash = createHash("sha256").update(source).digest("hex");
const generated = `// Generated by scripts/build_interior_planner.mjs from app.html. Do not edit.\n// Runtime SHA-256 ${hash}\n${source}\nself.planInteriorFloor=planInteriorFloor;\n`;
const path = "js/interior/planner-runtime.js";
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== generated)
    throw new Error(
      "Interior planner is stale. Run node scripts/build_interior_planner.mjs.",
    );
  console.log("Interior worker runtime is byte-for-byte current.");
} else {
  writeFileSync(path, generated);
  console.log(`Built ${path}: ${Buffer.byteLength(generated)} bytes.`);
}
